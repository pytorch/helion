# Warp-reduction call attribute names recognised by this pass.  Each maps
# to the identity element used for a floating-point per-thread V-fold
# accumulator (``_fold_identity`` gives an integer one's).
_REDUCE_IDENTITY: dict[str, str] = {
    "warp_reduction_sum": "0",
    "warp_reduction_max": "float('-inf')",
    "warp_reduction_min": "float('inf')",
}


# Per-reduction combine op used to fold V values into the accumulator
# before the single warp reduce.  ``a`` is the existing accumulator,
# ``b`` is the per-iter contribution.
_REDUCE_COMBINE: dict[str, str] = {
    "warp_reduction_sum": "({a}) + ({b})",
    "warp_reduction_max": "cute.math.max(({a}), ({b}), propagate_nan=True)",
    "warp_reduction_min": "cute.math.min(({a}), ({b}), propagate_nan=True)",
}


# The grouped-reduce helpers (``LANE_FOLD_REDUCES``) take the reduction op
# as a string literal in args[1] and the identity element in args[2]; the
# pass hoists them exactly like ``cute.arch.warp_reduction_*``.  Without
# this a multi-warp config (group_span > 32) runs a full two-barrier block
# reduction per V-lane per reduce.
_GROUPED_OP_TO_KEY: dict[str, str] = {
    "sum": "warp_reduction_sum",
    "max": "warp_reduction_max",
    "min": "warp_reduction_min",
}


def _looks_like_warp_reduce_call(node: ast.AST) -> tuple[str, ast.expr] | None:
    """If ``node`` is ``cute.arch.warp_reduction_<op>(INPUT, threads_in_group=T)``
    or a grouped-reduce helper call ``_cute_grouped_reduce_*(INPUT, '<op>',
    IDENTITY, ...)``, return ``("warp_reduction_<op>", INPUT)``.  Otherwise
    None.
    """
    if not isinstance(node, ast.Call):
        return None
    func = node.func
    if isinstance(func, ast.Name) and func.id in LANE_FOLD_REDUCES:
        if len(node.args) < 3:
            return None
        op_arg = node.args[1]
        if not (isinstance(op_arg, ast.Constant) and isinstance(op_arg.value, str)):
            return None
        op_key = _GROUPED_OP_TO_KEY.get(op_arg.value)
        if op_key is None:
            return None
        return op_key, node.args[0]
    if not isinstance(func, ast.Attribute):
        return None
    if func.attr not in _REDUCE_IDENTITY:
        return None
    val = func.value
    if not (isinstance(val, ast.Attribute) and val.attr == "arch"):
        return None
    if not node.args:
        return None
    return func.attr, node.args[0]


def _find_warp_reduce_in_expr(
    node: ast.AST,
) -> tuple[str, ast.expr, ast.Call] | None:
    """Find the first warp-reduction call inside ``node`` (depth-first).

    Returns ``(op, input_expr, call_node)`` or None.
    """
    if isinstance(node, ast.Call):
        match = _looks_like_warp_reduce_call(node)
        if match is not None:
            op, inp = match
            return op, inp, node
    for child in ast.iter_child_nodes(node):
        result = _find_warp_reduce_in_expr(child)
        if result is not None:
            return result
    return None


def _names_written(node: ast.stmt) -> set[str]:
    """Collect names written by an assignment statement (LHS Name targets)."""
    written: set[str] = set()
    if isinstance(node, ast.Assign):
        for target in node.targets:
            if isinstance(target, ast.Name):
                written.add(target.id)
            elif isinstance(target, (ast.Tuple, ast.List)):
                for elt in target.elts:
                    if isinstance(elt, ast.Name):
                        written.add(elt.id)
    return written


def _assignment_rhs(node: ast.stmt) -> ast.expr | None:
    if isinstance(node, ast.Assign):
        return node.value
    return None


def _compute_dependency_closure(
    body: list[ast.stmt],
    target_indices: set[int],
) -> set[int]:
    """Find all stmt indices that contribute to producing values used by
    statements at ``target_indices`` (transitive backward dep).

    Returns the closure including ``target_indices`` themselves.
    """
    # For each statement, gather the names it writes; record the LATEST def
    # for each name (last assignment wins, since that's what subsequent
    # reads would see).  For SSA-like dependency closure, we want: for each
    # name used by a stmt at idx, find the most recent prior stmt that
    # wrote that name.  Then chain.
    def_history: list[dict[str, int]] = []
    current: dict[str, int] = {}
    for i, stmt in enumerate(body):
        # Snapshot the def map BEFORE this stmt.
        def_history.append(dict(current))
        # Now update with this stmt's writes.
        for name in _names_written(stmt):
            current[name] = i

    # Now do BFS backward from target_indices.
    closure: set[int] = set(target_indices)
    worklist: list[int] = list(target_indices)
    while worklist:
        i = worklist.pop()
        stmt = body[i]
        defs_before = def_history[i]
        for name in names_read(stmt):
            j = defs_before.get(name)
            if j is not None and j not in closure:
                closure.add(j)
                worklist.append(j)
    return closure


def _name_explicit_fp32_reduce_inputs(
    body: list[ast.stmt], counter: list[int], running_sums: set[str]
) -> list[ast.stmt]:
    """Expose an explicit input conversion to the existing dependency proof.

    Keep the conversion as its own assignment. In particular, an earlier
    narrowing conversion that defines its operand must still execute before
    the FP32 reduction; replacing that earlier definition's cast would change
    the observable rounding. Failed hoist attempts leave the original AST
    unchanged.
    """
    used_names = {
        node.id
        for statement in body
        for node in ast.walk(statement)
        if isinstance(node, ast.Name)
    }
    # Only single-assignment scalar recipes can be exposed to the hoister.
    # A conditional write is not a definite definition. Even an unconditional
    # reset followed by an update is unsafe: the old scheduler could move the
    # invariant reset outside the V-loop and turn the update into a recurrence.
    # Count every syntactic write, including structured/augmented assignments,
    # then prove lexical dependencies using only ordinary scalar definitions.
    writes = Counter(
        node.id
        for statement in body
        for node in ast.walk(statement)
        if isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del))
    )
    definite: dict[str, int] = {}
    for index, statement in enumerate(body):
        if not (
            isinstance(statement, ast.Assign)
            and len(statement.targets) == 1
            and isinstance(statement.targets[0], ast.Name)
            and not any(isinstance(node, ast.NamedExpr) for node in ast.walk(statement))
        ):
            continue
        name = statement.targets[0].id
        if (
            writes[name] == 1
            and names_read(statement) & writes.keys() <= definite.keys()
        ):
            definite[name] = index
    result: list[ast.stmt] = []
    for index, statement in enumerate(body):
        rhs = _assignment_rhs(statement)
        found = _find_warp_reduce_in_expr(rhs) if rhs is not None else None
        if found is None:
            result.append(statement)
            continue
        _op, value, _call = found
        if not (
            isinstance(value, ast.Call)
            and ast.unparse(value.func) == "cutlass.Float32"
            and len(value.args) == 1
            and isinstance(value.args[0], ast.Name)
            and not value.keywords
        ):
            result.append(statement)
            continue
        input_name = value.args[0].id
        definition = definite.get(input_name)
        if input_name in running_sums or definition is None or definition >= index:
            # Naming a cast must not disguise a running accumulator or other
            # recurrence as a fresh per-lane reduction input.
            result.append(statement)
            continue
        while (name := f"_helion_vfold_input_{counter[0]}") in used_names:
            counter[0] += 1
        counter[0] += 1
        used_names.add(name)
        cloned = ast.parse(ast.unparse(statement)).body[0]
        cloned_rhs = _assignment_rhs(cloned)
        assert cloned_rhs is not None
        cloned_found = _find_warp_reduce_in_expr(cloned_rhs)
        assert cloned_found is not None
        cloned_call = cloned_found[2]
        result.append(statement_from_string(f"{name} = {ast.unparse(value)}"))
        cloned_call.args[0] = ast.Name(id=name, ctx=ast.Load())
        result.append(cloned)
    return result


def _try_hoist_one_vloop(
    vloop: ast.For,
    v: int,
    acc_name_counter: list[int],
    running_sums: set[str],
    input_dtypes: Mapping[str, str | None] | None = None,
) -> list[ast.stmt] | None:
    """Try to hoist warp reductions out of a single constexpr V-loop.

    Returns the new list of statements that REPLACES the V-loop, or None if
    the pattern doesn't match safely.  All AST mutations are performed on
    deep-copied nodes, so a failed attempt leaves the original V-loop
    untouched.
    """
    body = _name_explicit_fp32_reduce_inputs(vloop.body, acc_name_counter, running_sums)
    vec_lane_var: str | None = None
    if isinstance(vloop.target, ast.Name):
        vec_lane_var = vloop.target.id

    # ---- VALIDATION PHASE: no mutations yet. ----

    # Find all warp_reduction calls. Each is (idx, op, input_name).
    reduce_validate: list[tuple[int, str, str]] = []
    for idx, stmt in enumerate(body):
        rhs = _assignment_rhs(stmt)
        lhs = assigned_name(stmt)
        if rhs is None or lhs is None:
            continue
        found = _find_warp_reduce_in_expr(rhs)
        if found is None:
            continue
        op, input_expr, _call = found
        if not isinstance(input_expr, ast.Name):
            return None
        reduce_validate.append((idx, op, input_expr.id))

    if not reduce_validate:
        return None

    # V-dependence flow analysis (forward pass).
    #
    # A statement is "V-dependent" if its result varies per V-lane iteration.
    # Reads of the V-lane variable or of any V-dep name make a stmt V-dep.
    # CRUCIALLY: a warp-reduction statement's OUTPUT is scalar (one value
    # per warp, not per V-lane).  After hoisting, the reduce runs once and
    # downstream uses of its output are scalar — so we do NOT propagate
    # V-dep through reduce statements.
    reduce_stmt_indices = {idx for idx, _op, _name in reduce_validate}
    v_dependent: set[int] = set()
    if vec_lane_var is not None:
        v_defined_names: set[str] = set()
        for i, stmt in enumerate(body):
            reads = names_read(stmt)
            if vec_lane_var in reads or (reads & v_defined_names):
                v_dependent.add(i)
                if i not in reduce_stmt_indices:
                    # Only non-reduce stmts produce V-dep outputs.
                    v_defined_names.update(_names_written(stmt))

    # Validate each reduce: input must be V-dependent (otherwise pointless),
    # and have a clear definition.
    for idx, _op, input_name in reduce_validate:
        input_def_idx = -1
        for j in range(idx - 1, -1, -1):
            if input_name in _names_written(body[j]):
                input_def_idx = j
                break
        if input_def_idx < 0:
            return None
        if input_def_idx not in v_dependent:
            return None
        rhs = _assignment_rhs(body[input_def_idx])
        if rhs is None:
            return None

    # Trailing stmts after last reduce: bail if any are V-dependent.
    last_reduce_idx = reduce_validate[-1][0]
    for i in range(last_reduce_idx + 1, len(body)):
        if i in v_dependent:
            return None

    # Stmts BEFORE first reduce that are V-dependent but not in any reduce's
    # closure: bail (we'd lose them).  Compute closure for each reduce's
    # input.
    closures: list[set[int]] = []
    for idx, _op, input_name in reduce_validate:
        input_def_idx = -1
        for j in range(idx - 1, -1, -1):
            if input_name in _names_written(body[j]):
                input_def_idx = j
                break
        closure = _compute_dependency_closure(body, {input_def_idx})
        closures.append(closure)
    all_closures: set[int] = set()
    for c in closures:
        all_closures |= c
    # The per-element values the V-loop computes for something else than a
    # reduction ahead of the first one, such as the elements of a store that
    # follows the loop, run in the first reduction's fold loop, in their
    # order: a where's result stored and summed,
    #     v_2 = cutlass.BFloat16(tmp3)
    #     _tile_store_vals_1_0.append(cutlass.BFloat16(v_2).bitcast(cutlass.Uint16))
    #     _mask_to = cutlass.Float32(tmp3) if mask_1 else cutlass.Float32(0)
    #     sum_1 = cutlass.Float32(_cute_grouped_reduce_shared_two_stage(_mask_to, 'sum', ...))
    # kept its reduction in the V-loop, once per element, and the config
    # failed in fold_lane_reductions ("reduction in lane_1 is not a plain
    # assignment of the lane body"). So did a store the vector-loop sink
    # leaves per element, an r-vectorized copy and sum over r whose output
    # is not contiguous along r:
    #     v_1 = cutlass.BFloat16(v_0)
    #     (out0.iterator + ... + cutlass.Int32(indices_2) * ...).store(cutlass.BFloat16(v_1))
    #     sum_1 = cutlass.Float32(cute.arch.warp_reduction_sum(v_0, threads_in_group=32))
    # which runs in the fold loop too, in its order against the element's
    # loads, when the loop holds one reduction (element_store()). A later
    # fold loop would load its elements after every store of the first one,
    # where a buffer Inductor updates in place reads the stored value: with
    # two reductions, a store keeps the loop.
    single_reduction = len(reduce_validate) == 1
    side = [
        i
        for i in range(reduce_validate[0][0])
        if i in v_dependent and i not in all_closures
    ]
    if not all(
        _is_side_computation(body[i]) or (single_reduction and element_store(body[i]))
        for i in side
    ):
        return None
    # Between two reductions such a statement would run in no fold loop, and
    # moving it into the next one would reorder its elements against the
    # first fold loop's (two appends to one list interleave per element):
    #     a = cutlass.Float32(_v0[vec_lane_1])
    #     sum_1 = cutlass.Float32(cute.arch.warp_reduction_sum(a, ...))
    #     _tile_store_vals_1_0.append(cutlass.BFloat16(b).bitcast(cutlass.Uint16))
    #     sum_2 = cutlass.Float32(cute.arch.warp_reduction_sum(c, ...))
    # lost the append, and the store after the loop wrote an empty list.  The
    # loop keeps its per-element reduces.
    if any(
        i in v_dependent and i not in all_closures and i not in reduce_stmt_indices
        for i in range(reduce_validate[0][0] + 1, last_reduce_idx)
    ):
        return None

    # ---- COMMIT PHASE: build new statements. ----
    new_stmts: list[ast.stmt] = []

    # Re-find call_nodes and stmts on a re-parsed copy of the body so we
    # don't mutate the original V-loop's children.  ``ast.unparse`` +
    # ``ast.parse`` avoids the ``copy.deepcopy`` failure on ExtendedAST.
    body_copy: list[ast.stmt] = []
    for s in body:
        text = ast.unparse(s)
        parsed = ast.parse(text).body[0]
        body_copy.append(parsed)
    reduce_info_copy: list[tuple[int, str, str, str, ast.Call, ast.stmt]] = []
    for idx, stmt in enumerate(body_copy):
        rhs = _assignment_rhs(stmt)
        lhs = assigned_name(stmt)
        if rhs is None or lhs is None:
            continue
        found = _find_warp_reduce_in_expr(rhs)
        if found is None:
            continue
        op, input_expr, call_node = found
        assert isinstance(input_expr, ast.Name)
        reduce_info_copy.append((idx, lhs, op, input_expr.id, call_node, stmt))

    # Build a schedule:
    #  - For each stmt in body, decide whether it's scalar (emit once) or
    #    V-dep (emit inside a V-loop).  V-dep stmts get assigned to whichever
    #    reduce's V-loop they belong to (based on closure membership).  A
    #    V-dep stmt MAY belong to multiple V-loops (e.g. ``values`` extracted
    #    from the load is read by both reduces).
    #  - Reduce stmts are emitted after their V-loop in scalar scope.
    #  - Scalar stmts not in any closure go where they appear in original
    #    order, relative to the surrounding reduces.

    # For each reduce, determine which V-dep stmts belong in its V-loop.
    # Exclude all reduce stmts from V-loop bodies — they've been hoisted to
    # scalar scope (the reduce call produces a scalar that downstream code
    # uses; running it inside the V-loop would re-do the warp reduce V times,
    # which defeats the whole purpose of this pass).
    reduce_stmt_indices_in_body = {
        r_idx for r_idx, _l, _o, _n, _c, _s in reduce_info_copy
    }
    v_loop_members: list[set[int]] = []
    for c in closures:
        members = (c & v_dependent) - reduce_stmt_indices_in_body
        v_loop_members.append(members)
    # The side statements run in the first fold loop with the per-element
    # values they read, which may belong to a later reduction's closure
    # only: in
    #     b = cutlass.Float32(_v1[vec_lane_1])
    #     _tile_store_vals_1_0.append(cutlass.BFloat16(b).bitcast(cutlass.Uint16))
    #     sum_1 = cutlass.Float32(cute.arch.warp_reduction_sum(a, ...))
    #     sum_2 = cutlass.Float32(cute.arch.warp_reduction_sum(b, ...))
    # ``b`` is computed in both fold loops; without it the first one appended
    # a ``b`` it had not defined yet.
    side_closure = _compute_dependency_closure(body, set(side)) if side else set()
    v_loop_members[0] |= (side_closure & v_dependent) - reduce_stmt_indices_in_body

    # Compute "scalar emission position" for each scalar stmt: emit after
    # the last reduce idx < stmt_idx (or before all reduces if none).  We
    # mark each scalar stmt with a "phase" number: 0 = before first reduce,
    # k = after reduce (k-1).
    def scalar_phase(i: int) -> int:
        phase = 0
        for r_idx, _l, _o, _n, _c, _s in reduce_info_copy:
            if r_idx < i:
                phase += 1
            else:
                break
        return phase

    # Group scalar stmts by phase.
    phase_scalars: dict[int, list[int]] = {}
    for i in range(len(body_copy)):
        is_reduce = any(r_idx == i for r_idx, *_ in reduce_info_copy)
        if i in v_dependent or is_reduce:
            continue
        phase = scalar_phase(i)
        phase_scalars.setdefault(phase, []).append(i)

    # Emit phase 0 scalars (before first reduce).
    for j in sorted(phase_scalars.get(0, [])):
        new_stmts.append(body_copy[j])

    for reduce_pos, (
        idx,
        _lhs,
        op,
        input_name,
        call_node,
        reduce_stmt,
    ) in enumerate(reduce_info_copy):
        # Find input def idx in body_copy.
        input_def_idx = -1
        for j in range(idx - 1, -1, -1):
            if input_name in _names_written(body_copy[j]):
                input_def_idx = j
                break
        assert input_def_idx >= 0
        input_def_rhs = _assignment_rhs(body_copy[input_def_idx])
        assert input_def_rhs is not None

        combine_template = _REDUCE_COMBINE[op]
        fold_dtype = _fold_dtype(
            call_node, input_name, input_def_rhs, input_dtypes or {}
        )
        # The dtype the accumulator is held in: the fold's, or the float
        # that carries an integer's extremum (``extremum_carrier`` says
        # why), which is converted back for the reduce.
        carrier = None if fold_dtype is None else _fold_carrier(op, fold_dtype)
        if carrier == "cutlass.Float32":
            # ``cute.math.max(propagate_nan=True)`` lowers to compares and
            # selects; the hardware FMNMX.NaN is one instruction and, like the
            # warp shuffle reduction, propagates NaN as torch.amax does.
            if op == "warp_reduction_max":
                combine_template = "cute.arch.fmax(({a}), ({b}), nan=True)"
            elif op == "warp_reduction_min":
                combine_template = "cute.arch.fmin(({a}), ({b}), nan=True)"
        # Decide how to hoist the reduce.  Three cases:
        #
        #  (b) The input is a matmul-fallback PER-THREAD RUNNING SUM, flagged
        #      authoritatively by the producer (``_emit_cute_matmul`` records
        #      the ``dot_acc`` var on the DeviceFunction).  Such a value
        #      already accumulates across V-lanes inside its own
        #      ``acc = acc + product`` def, so a per-thread partial + ONE
        #      cross-thread sum reduce is exactly the full sum: keep the def in
        #      the loop and reduce its FINAL value once.  V-folding it again
        #      would double-count.
        #
        #  (c) The input is loop-carried (its in-loop def reads itself) but NOT
        #      a flagged running sum — a rescaled / non-sum recurrence such as
        #      ``di = di * alpha + ...`` or ``mi = maximum(mi, ...)``.  Neither
        #      the V-fold (would fold the carried value) nor reduce-once (sum
        #      identity doesn't hold) is valid, so leave the V-loop untouched.
        #
        #  (a) Otherwise the input is a fresh per-lane value (softmax /
        #      layernorm ``amax``/``sum``): build a ``_helion_vfold_acc`` and
        #      fold each lane in, then ONE warp reduce.  [the original path]
        input_def = body_copy[input_def_idx]
        input_is_running_sum = input_name in running_sums
        if not input_is_running_sum and input_name in names_read(input_def):
            return None  # case (c): loop-carried but not a known running sum
        input_is_loop_carried = input_is_running_sum

        vloop_body: list[ast.stmt] = []
        v_members = sorted(v_loop_members[reduce_pos])
        acc_dtype: str | None = None
        reduce_input = input_name
        if input_is_loop_carried:
            acc_name = input_name
            for j in v_members:
                vloop_body.append(body_copy[j])
        else:
            # The accumulator takes the dtype the reduce combines in.  A
            # reduce that does not say which keeps its loop: an accumulator
            # of another dtype would round every lane's value to it.
            acc_dtype = fold_dtype
            if acc_dtype is None or carrier is None:
                return None
            identity = _fold_identity(op, acc_dtype)
            acc_name = f"_helion_vfold_acc_{acc_name_counter[0]}"
            acc_name_counter[0] += 1
            acc_init_expr = f"{carrier}({identity})"
            new_stmts.append(statement_from_string(f"{acc_name} = {acc_init_expr}"))
            reduce_input = (
                acc_name if carrier == acc_dtype else f"{acc_dtype}({acc_name})"
            )

            # V-loop body: all V-dep stmts in this reduce's closure, in
            # original order.  When we hit input_def_idx, also emit acc
            # combine after it: the input's definition converted to the acc
            # dtype, any conversion it holds included (a narrower one rounds
            # the value the loop reduced).  Keep the
            # original input def stmt — it may be read by later V-loop stmts
            # (the dependency closure can include paths through it), and the
            # CuTe DSL will DCE it if unused.
            for j in v_members:
                vloop_body.append(body_copy[j])
                if j == input_def_idx:
                    input_rhs = _assignment_rhs(body_copy[j])
                    assert input_rhs is not None
                    promoted_rhs = _rewrite_cast_wrapper(input_rhs, acc_dtype)
                    if carrier != acc_dtype:
                        promoted_rhs = _rewrite_cast_wrapper(promoted_rhs, carrier)
                    rhs_text = ast.unparse(promoted_rhs)
                    combine_expr = combine_template.format(a=acc_name, b=rhs_text)
                    vloop_body.append(
                        statement_from_string(f"{acc_name} = {combine_expr}")
                    )

        target_text = ast.unparse(vloop.target)
        iter_text = ast.unparse(vloop.iter)
        new_vloop_template = ast.parse(
            f"for {target_text} in {iter_text}:\n    pass"
        ).body[0]
        assert isinstance(new_vloop_template, ast.For)
        new_vloop_template.body = vloop_body
        ast.copy_location(new_vloop_template, vloop)
        ast.fix_missing_locations(new_vloop_template)
        new_stmts.append(new_vloop_template)

        # Emit the reduce stmt with input -> acc, in the reduce's dtype.
        new_reduce_stmt = _replace_reduce_input(
            reduce_stmt, call_node, reduce_input, acc_dtype
        )
        if new_reduce_stmt is None:
            return None
        new_stmts.append(new_reduce_stmt)

        # Emit phase (reduce_pos + 1) scalars.
        for j in sorted(phase_scalars.get(reduce_pos + 1, [])):
            new_stmts.append(body_copy[j])

    return new_stmts


def _is_side_computation(stmt: ast.stmt) -> bool:
    """Whether ``stmt`` computes a register value (an assignment of a name)
    or appends one to a trace-time list (``vals.append(...)``), with no call
    but those proven free of observable effects
    (``_is_proven_relocatable_call``: conversions, bitcasts, math, loads)."""
    if isinstance(stmt, ast.Assign):
        if len(stmt.targets) != 1 or not isinstance(stmt.targets[0], ast.Name):
            return False
        value: ast.expr = stmt.value
    elif (
        isinstance(stmt, ast.Expr)
        and isinstance(stmt.value, ast.Call)
        and isinstance(stmt.value.func, ast.Attribute)
        and stmt.value.func.attr == "append"
        and isinstance(stmt.value.func.value, ast.Name)
        and len(stmt.value.args) == 1
        and not stmt.value.keywords
    ):
        value = stmt.value.args[0]
    else:
        return False
    return all(
        _is_proven_relocatable_call(node, allow_load=True)
        for node in ast.walk(value)
        if isinstance(node, ast.Call)
    )


def element_store(stmt: ast.stmt) -> bool:
    """Whether ``stmt`` stores one value through a pointer,
    ``ptr.store(value)``, or does so under a mask, ``if mask: ptr.store(value)``
    (``else: pass``), with no call in its address, value or mask but those
    proven free of observable effects (``_is_proven_relocatable_call``)."""
    if isinstance(stmt, ast.If):
        if len(stmt.body) != 1 or not all(
            isinstance(other, ast.Pass) for other in stmt.orelse
        ):
            return False
        if not all(
            _is_proven_relocatable_call(node, allow_load=True)
            for node in ast.walk(stmt.test)
            if isinstance(node, ast.Call)
        ):
            return False
        stmt = stmt.body[0]
    if not (
        isinstance(stmt, ast.Expr)
        and isinstance(store := stmt.value, ast.Call)
        and isinstance(store.func, ast.Attribute)
        and store.func.attr == "store"
        and len(store.args) == 1
        and not store.keywords
    ):
        return False
    return all(
        _is_proven_relocatable_call(node, allow_load=True)
        for node in ast.walk(store)
        if isinstance(node, ast.Call) and node is not store
    )


def _rewrite_cast_wrapper(rhs: ast.expr, new_dtype: str) -> ast.expr:
    """Convert ``rhs`` to ``new_dtype``, recursing into IfExp branches:
    ``cutlass.Float16(values) if mask else cutlass.Float16(-inf)`` becomes
    ``cutlass.Float32(cutlass.Float16(values)) if mask else
    cutlass.Float32(cutlass.Float16(-inf))``.

    A conversion that ``rhs`` holds is kept and converted, never replaced by
    ``new_dtype``'s: it rounds an operand wider than itself
    (``x.to(torch.float16)`` of an fp32 ``x``), and the fold has to add the
    values the loop reduced; where the operand has its dtype already it costs
    nothing.  A conversion to ``new_dtype`` itself is left as it is.
    """
    if isinstance(rhs, ast.IfExp):
        new_body = _rewrite_cast_wrapper(rhs.body, new_dtype)
        new_orelse = _rewrite_cast_wrapper(rhs.orelse, new_dtype)
        return ast.IfExp(test=rhs.test, body=new_body, orelse=new_orelse)
    if (
        isinstance(rhs, ast.Call)
        and isinstance(rhs.func, ast.Attribute)
        and ast.unparse(rhs.func) == new_dtype
    ):
        return rhs
    return ast.parse(f"{new_dtype}({ast.unparse(rhs)})").body[0].value  # type: ignore[union-attr]


# The floating-point dtypes narrower than fp32 (the half and fp8 formats
# ``CuteBackend.dtype_str`` names): a reduction in one of them folds in fp32,
# which holds each of its values exactly.
_NARROW_FLOAT_DTYPES = (
    "cutlass.Float16",
    "cutlass.BFloat16",
    "cutlass.Float8E4M3FN",
    "cutlass.Float8E5M2",
    "cutlass.Float8E8M0FNU",
)
# The other dtypes a V-fold accumulates in: fp32, float64 and the integers,
# whose identities ``_fold_identity`` writes (not ``cutlass.Boolean``, whose
# constructor turns an infinity into True).
_FOLD_DTYPE = re.compile(r"cutlass\.(?:Float(?:32|64)|(?:Int|Uint)\d+)")


def _fold_dtype(
    call: ast.Call,
    input_name: str,
    input_def: ast.expr,
    input_dtypes: Mapping[str, str | None],
) -> str | None:
    """The dtype the V-fold of the reduce ``call`` converts each lane's value
    to and reduces in, or None when nothing says which dtype the reduce
    combines in.  (The accumulator has that dtype, or holds it in a carrier:
    ``_fold_carrier``.)

    A grouped helper names that dtype in its identity argument: the helper
    types its shared-memory staging and its masked lanes with it, and the
    emitters convert the input to it.  A direct ``cute.arch.warp_reduction_*``
    has no such argument: its emitter records the reduction's dtype under the
    name of the value it reduces (``CuteLaneState.reduce_input_dtypes``), and
    without a record the dtype is known when that value's definition is a
    conversion (``cutlass.Float32(x)``), as for an input this pass named
    (``_name_explicit_fp32_reduce_inputs``).  The text of any other
    definition (a load, a product, a call) does not show its dtype.

    A reduction in a floating-point dtype narrower than fp32 (half precision,
    fp8) accumulates in fp32, to which its values convert exactly: the
    downstream uses convert to fp32 anyway, an fp16 max is no cheaper than an
    fp32 max on a B200, and a sum keeps more of its addends.  No other dtype
    is changed.
    """
    if isinstance(call.func, ast.Name):
        dtype = _dtype_constructor(call.args[2])
    elif input_name in input_dtypes:
        dtype = input_dtypes[input_name]
    else:
        dtype = _dtype_constructor(input_def)
    if dtype in _NARROW_FLOAT_DTYPES:
        return "cutlass.Float32"
    if dtype is None or not _FOLD_DTYPE.fullmatch(dtype):
        return None
    return dtype


def _dtype_constructor(node: ast.expr) -> str | None:
    """``cutlass.<Dtype>`` when ``node`` is a conversion
    ``cutlass.<Dtype>(x)`` (``_strip_dtype_wrap`` peels one), else None."""
    if isinstance(node, ast.Call) and _strip_dtype_wrap(node) is not node:
        return ast.unparse(node.func)
    return None


def _fold_identity(op: str, dtype: str) -> str:
    """The literal the V-fold of a reduction in ``dtype`` starts from: an
    integer's lowest or highest value for its maximum or minimum
    (``extremum_identity``), else ``_REDUCE_IDENTITY``."""
    if op != "warp_reduction_sum":
        identity = extremum_identity(dtype, op == "warp_reduction_max")
        if identity is not None:
            return identity
    return _REDUCE_IDENTITY[op]


def _fold_carrier(op: str, dtype: str) -> str:
    """The dtype the V-fold of a reduction in ``dtype`` holds its
    accumulator in: ``dtype``, but a float that holds it for the maximum or
    minimum of an integer of at most 32 bits (``extremum_carrier``).  A sum
    keeps its dtype: an integer sum wraps, which no floating-point sum does."""
    return dtype if op == "warp_reduction_sum" else extremum_carrier(dtype)


def _replace_reduce_input(
    reduce_stmt: ast.stmt,
    call_node: ast.Call,
    acc_input: str,
    acc_dtype: str | None = None,
) -> ast.stmt | None:
    """Return a copy of ``reduce_stmt`` with ``call_node``'s first arg replaced
    by the expression ``acc_input``: the accumulator, or its conversion to
    the reduce's dtype.

    For grouped-reduce helper calls, the identity element (args[2]) must
    match the input dtype (the helpers derive their smem dtype from it), so
    when ``acc_dtype`` is given the identity is converted to it (e.g.
    ``cutlass.BFloat16(float('-inf'))`` ->
    ``cutlass.Float32(cutlass.BFloat16(float('-inf')))``).
    """
    if not isinstance(reduce_stmt, ast.Assign):
        return None

    class _InputRewriter(ast.NodeTransformer):
        def __init__(self) -> None:
            self.done = False

        def visit_Call(self, node: ast.Call) -> ast.AST:
            if node is call_node and not self.done:
                self.done = True
                new_args = [ast.parse(acc_input, mode="eval").body, *node.args[1:]]
                if (
                    acc_dtype is not None
                    and isinstance(node.func, ast.Name)
                    and node.func.id in LANE_FOLD_REDUCES
                    and len(new_args) >= 3
                ):
                    new_args[2] = _rewrite_cast_wrapper(new_args[2], acc_dtype)
                new_call = ast.Call(
                    func=node.func, args=new_args, keywords=node.keywords
                )
                return ast.copy_location(new_call, node)
            return cast("ast.AST", self.generic_visit(node))

    rewriter = _InputRewriter()
    new_stmt = rewriter.visit(reduce_stmt)
    if not rewriter.done:
        return None
    assert isinstance(new_stmt, ast.stmt)
    ast.fix_missing_locations(new_stmt)
    return new_stmt


def _per_lane_reduce_escape(vloop: ast.For) -> str | None:
    """Why a V-loop the hoist leaves in place computes the wrong values, or
    None.

    Left in a vector lane loop (``vec_lane_*``: the elements of one packet,
    which the tile strategy walks), each cross-thread reduce combines one V
    lane of every thread: its result is a partial of the reduction over the
    loop's block.  (Other constexpr loops, a fixed recurrence's tokens say,
    reduce once per iteration by design.)
    A value computed from a partial and the lane's own elements
    (``v - sum``) is per element; storing it, carrying it across the lanes
    (``acc = acc + exp(v) + sum``) or keeping it past the loop keeps the
    partial where the program has the whole reduction.  Partials folded into
    a later reduce (Welford's centered squares) or into values the same in
    every lane (Welford's chunk merge, online softmax's rescaled sums)
    combine as the hoisted form would.
    """
    if not (
        isinstance(vloop.target, ast.Name) and vloop.target.id.startswith("vec_lane")
    ):
        return None
    lane_values = {vloop.target.id}  # names that differ between the V lanes
    partials: set[str] = set()  # reduce results and names computed from them
    lane_partials: dict[str, bool] = {}  # lane-varying partial -> read since
    carried: set[str] = set()  # names the body reads before writing
    written: set[str] = set()
    for stmt in vloop.body:
        reads = names_read(stmt)
        writes = names_written(stmt)
        carried |= reads - written
        written |= writes
        for name in reads & lane_partials.keys():
            lane_partials[name] = True
        reduces = any(
            isinstance(node, ast.Assign)
            and _find_warp_reduce_in_expr(node.value) is not None
            for node in ast.walk(stmt)
        )
        from_partial = reduces or bool(reads & partials)
        if from_partial:
            partials |= writes
        if not reads & lane_values or (reduces and isinstance(stmt, ast.Assign)):
            continue
        lane_values |= writes
        if not from_partial:
            continue
        if not isinstance(stmt, ast.Assign):
            # A store, or a branch or loop around a reduce or a partial.
            return "a statement other than an assignment reads one V lane's partial"
        lane_partials.update(dict.fromkeys(writes, False))
    for name, read in lane_partials.items():
        if name in carried:
            return f"{name} carries one V lane's partial into the next"
        if not read:
            return f"{name} keeps one V lane's partial past the loop"
    return None


def _hoist_in_body(
    body: list[ast.stmt],
    acc_counter: list[int],
    running_sums: set[str],
    unfoldable_vec_lanes: set[str],
    input_dtypes: Mapping[str, str | None],
) -> list[ast.stmt]:
    """Walk ``body`` recursively; for each constexpr V-loop containing warp
    reductions, replace it with the V-fold + hoisted-reduce form.  A V-loop
    named in ``unfoldable_vec_lanes`` iterates another block than its
    reductions reduce (one output element per V lane) and is left alone.
    """

    def walk(stmts: list[ast.stmt]) -> list[ast.stmt]:
        return _hoist_in_body(
            stmts, acc_counter, running_sums, unfoldable_vec_lanes, input_dtypes
        )

    new_body: list[ast.stmt] = []
    for stmt in body:
        if isinstance(stmt, ast.For):
            stmt.body = walk(stmt.body)
            stmt.orelse = walk(stmt.orelse)
            match = constexpr_v_loop(stmt)
            if match is not None and not (
                isinstance(stmt.target, ast.Name)
                and stmt.target.id in unfoldable_vec_lanes
            ):
                vloop, v = match
                replacement = _try_hoist_one_vloop(
                    vloop, v, acc_counter, running_sums, input_dtypes
                )
                if replacement is not None:
                    new_body.extend(replacement)
                    continue
                reason = _per_lane_reduce_escape(vloop)
                if reason is not None:
                    raise exc.BackendUnsupported(
                        "cute", f"reduction left in a vector lane loop: {reason}"
                    )
            new_body.append(stmt)
        elif isinstance(stmt, ast.If):
            stmt.body = walk(stmt.body)
            stmt.orelse = walk(stmt.orelse)
            new_body.append(stmt)
        elif isinstance(stmt, (ast.With, ast.FunctionDef)):
            stmt.body = walk(stmt.body)
            new_body.append(stmt)
        else:
            new_body.append(stmt)
    return new_body


def hoist_warp_reduce_from_vloop(
    body: list[ast.stmt],
    *,
    running_sum_accumulators: set[str] | None = None,
    rename_groups: dict[str, str] | None = None,
    unfoldable_vec_lanes: set[str] | None = None,
    reduce_input_dtypes: Mapping[str, str | None] | None = None,
) -> list[ast.stmt]:
    """Apply the hoist pass to a list of kernel-body statements.

    Returns the (possibly modified) body.  Safe to call on any kernel body
    — only rewrites the well-defined "warp reduction inside constexpr V-loop"
    pattern.

    ``running_sum_accumulators`` is the set of matmul-fallback per-thread
    running-sum variable names (recorded by ``_emit_cute_matmul`` on the
    ``DeviceFunction``).  A reduce whose input is one of these is reduced ONCE
    after the loop rather than V-folded — the producer tells us authoritatively
    that the value already accumulates across V-lanes, so we don't re-derive it
    by pattern-matching the AST.

    ``unfoldable_vec_lanes`` names the V-loops that enclose a reduction over
    another block (recorded by the reduction lowering): their lanes are
    distinct output elements, which a V-fold would combine.

    ``reduce_input_dtypes`` maps the name of a value that a direct
    ``cute.arch.warp_reduction_*`` reduces to the dtype the reduction
    combines in (recorded by ``CuteBackend.reduction_expr``; None for a name
    recorded with two dtypes).  A V-fold's accumulator takes that dtype, or
    the one a grouped helper's identity argument names (``_fold_dtype``); a
    reduce whose dtype nothing states keeps its loop.  The maximum or minimum
    of an integer of at most 32 bits is held in a float that holds it and
    converted back for the reduce (``_fold_carrier``).

    After the per-V-loop hoist, a second walk collapses the remaining
    per-lane-iteration reduces: a static lane loop that runs ``REDUCE`` +
    ``carry = combine(carry, result)`` once per iteration is rewritten to
    fold the per-thread accumulator across ALL lane iterations and reduce
    ONCE after the loop.  For multi-warp grouped reductions this removes
    ``L-1`` two-barrier shared-memory reductions per sweep.
    """
    new_body = _hoist_in_body(
        body,
        [0],
        running_sum_accumulators or set(),
        unfoldable_vec_lanes or set(),
        reduce_input_dtypes or {},
    )
    return _collapse_in_body(new_body, new_body, rename_groups or {})


