# One Helion kernel of Inductor's output module: its source string, which the
# module loads with PyCodeCache.load(<name>_source).kernel.
SOURCE_RE = re.compile(r'^(\w+)_source = """\\\n(.*?)"""$', re.MULTILINE | re.DOTALL)
# The key fields a pinned config is matched on (LooseAutotuneCacheKey's).
MATCHED_FIELDS = (
    "kernel_source_hash",
    "specialization_key",
    "hardware",
    "extra_cache_key",
)

HEADER = '''\
"""helion.inductor's output code for better-benchmark's {repro_id} at shape
{shape}, each Helion kernel pinned to a tuned config ({configs_note}).

Generated by inductor_pretuned.py; regenerate it rather than edit it:

    HELION_BACKEND=cute python benchmarks/cute/better_benchmark/inductor_pretuned.py \\\\
        {repro_id} --shape {shape} --configs-from DIR
"""

REPRO = {repro_id!r}
SHAPE = {shape!r}
CONFIGS_FROM = {configs_note!r}
# helion.inductor's source hash (common.inductor_source_hash()) when written.
SOURCE_HASH = {source_hash!r}

'''

FOOTER = '''

def forward(inputs):
    """bench.py's entry: the repro's tensor inputs, in order, are the graph's
    inputs that call() takes."""
    return call([x for x in inputs if isinstance(x, torch.Tensor)])
'''


def config_entries(directory: Path | None) -> list[dict[str, Any]]:
    """The Helion autotune cache entries in ``directory`` (none for None)."""
    if directory is None:
        return []
    entries = [json.loads(p.read_text()) for p in directory.glob("*.best_config")]
    if not entries:
        raise FileNotFoundError(f"no *.best_config entries in {directory}")
    return entries


def matching_entry(
    entries: list[dict[str, Any]], key_fields: dict[str, str]
) -> dict[str, Any] | None:
    """The entry whose key matches ``key_fields`` on MATCHED_FIELDS, the
    fields of a cache key as ``LocalAutotuneCache.put`` records them (each
    field's str); None when none does. Entries that match but name different
    configs are an error: they cannot tell which one to pin."""
    found = [
        entry
        for entry in entries
        if all(entry["key"]["fields"].get(k) == key_fields[k] for k in MATCHED_FIELDS)
    ]
    configs = {
        json.dumps(json.loads(entry["config"]), sort_keys=True) for entry in found
    }
    if len(configs) > 1:
        raise ValueError(
            f"{len(configs)} different configs match kernel "
            f"{key_fields['kernel_source_hash'][:12]}"
        )
    return found[0] if found else None


@contextlib.contextmanager
def configs_from(
    entries: list[dict[str, Any]], *, required: bool, matched: list[str]
) -> Iterator[None]:
    """Within the block, a Helion kernel that looks up its autotune cache
    gets the config of the entry ``matching_entry`` finds for its key,
    before the cache's own lookup; ``matched`` collects their source hashes.
    With ``required``, a kernel without one raises LookupError instead of
    autotuning."""
    from helion.autotuner import local_cache

    original = local_cache.LocalAutotuneCache.get

    def get(self: local_cache.LocalAutotuneCache) -> local_cache.Config | None:
        fields = {k: str(getattr(self.key, k)) for k in MATCHED_FIELDS}
        entry = matching_entry(entries, fields)
        if entry is not None:
            self._validate_config_policy(entry)
            matched.append(fields["kernel_source_hash"])
            return local_cache.Config.from_json(entry["config"])
        if required:
            raise LookupError(
                f"no config for kernel {fields['kernel_source_hash'][:12]} "
                "(--require-configs)"
            )
        return original(self)

    local_cache.LocalAutotuneCache.get = get
    try:
        yield
    finally:
        local_cache.LocalAutotuneCache.get = original


# The decorator line of a Helion kernel source, and the settings in it that
# pinned_decorator() keeps.
DECORATOR_RE = re.compile(r"^@helion\.kernel\(.*\)$", re.MULTILINE)


def pinned_decorator(source: str) -> str:
    """The decorator that pins the kernel of ``source``, a Helion kernel
    module of Inductor's output, to the config it ran with: PyCodeCache
    hands back the module the output loaded, so its kernel holds the bound
    kernel of that call. The decorator keeps the kernel's backend."""
    from torch._inductor.codecache import PyCodeCache

    kernel = PyCodeCache.load(source).kernel
    bound = list(kernel._bound_kernels.values())
    if not bound or bound[0]._config is None:
        raise RuntimeError("a Helion kernel of the output was never called")
    configs = {repr(b._config) for b in bound}
    if len(configs) != 1:
        raise RuntimeError(f"a Helion kernel ran with {len(configs)} configs")
    decorator = bound[0].format_kernel_decorator(bound[0]._config, bound[0].settings)
    if "backend=" not in decorator:
        decorator = decorator.replace(
            "@helion.kernel(", f"@helion.kernel(backend={bound[0].settings.backend!r}, "
        )
    return with_settings(decorator, bound[0].settings)


def with_settings(decorator: str, settings: Settings) -> str:
    """``decorator`` with the fast_math and dot_precision that the kernel ran
    with (``settings``), which format_kernel_decorator() leaves out: as its
    decorator set them, or, where it set none, as HELION_FAST_MATH and
    TRITON_F32_DEFAULT did. Written out, the file replays them in any
    environment, a campaign job (which clears HELION_*) among them."""
    for name, value in (
        ("dot_precision", settings.dot_precision),
        ("fast_math", settings.fast_math),
    ):
        if f"{name}=" not in decorator:
            decorator = decorator.replace(
                "@helion.kernel(", f"@helion.kernel({name}={value!r}, ", 1
            )
    return decorator


def pin(
    code: str, decorator_of: Callable[[str], str] = pinned_decorator
) -> tuple[str, int]:
    """``code``, an Inductor output module, with the decorator of each Helion
    kernel source in it replaced by ``decorator_of(source)``, and how many
    kernels it pinned."""

    def replace(match: re.Match[str]) -> str:
        name, text = match.group(1), match.group(2)
        # The source as Python reads the literal, the one PyCodeCache loaded:
        # helion.inductor escapes its backslashes and triple quotes
        # (codegen.scheduling), and the decorator written back is escaped so.
        source = ast.literal_eval(f'"""\\\n{text}"""')
        lines = text.split("\n")
        (index,) = [
            i for i, line in enumerate(lines) if line.startswith("@helion.kernel(")
        ]
        decorator = decorator_of(source)
        lines[index] = decorator.replace("\\", "\\\\").replace('"""', '\\"""')
        return f'{name}_source = """\\\n' + "\n".join(lines) + '"""'

    return SOURCE_RE.subn(replace, code)


def identical(a: torch.Tensor, b: torch.Tensor) -> bool:
    """Whether two outputs are the same bits in the same layout: dtype, shape
    and strides alike, and each element's bits (-0.0 is not 0.0, and a NaN
    matches only a NaN of its bits)."""
    import torch

    if (a.dtype, a.shape, a.stride()) != (b.dtype, b.shape, b.stride()):
        return False
    if a.dtype.is_floating_point:
        bits = {1: torch.uint8, 2: torch.int16, 4: torch.int32, 8: torch.int64}
        a, b = a.view(bits[a.element_size()]), b.view(bits[b.element_size()])
    return torch.equal(a, b)


def check_reproduced(
    output: Path, expected: object, again: object, actual: object
) -> None:
    """Raise unless ``actual``, the outputs of the written module, are the
    compiled call's (``expected``): bit for bit, in the same layout
    (identical()), where the compiled call reproduced itself so in a second
    call (``again``), and where it
    did not, within four times the largest difference between its two calls
    plus 1e-5 relative (torch.testing adds the two): an atomic accumulation's
    order moves the low bits,
    by up to 1.5e-5 relative (one ulp of a small sum) in
    sum_sum_sum_d2c97d17f3dc's float32 column sums, by more than one pair of
    calls shows."""
    import torch

    expected, again, actual = (
        common.flatten_outputs(v) for v in (expected, again, actual)
    )
    if len(actual) != len(expected):
        raise RuntimeError(
            f"{output} returns {len(actual)} outputs, not {len(expected)}"
        )
    for index, (e, e2, a) in enumerate(zip(expected, again, actual, strict=True)):
        if identical(e, e2):
            if not identical(a, e):
                raise RuntimeError(
                    f"{output} does not reproduce output {index} of the compiled call"
                )
        else:
            # The tolerance is for an atomic accumulation's order, not for a
            # layout: dtype, shape and strides alike first.
            if (a.dtype, a.shape, a.stride()) != (e.dtype, e.shape, e.stride()):
                raise RuntimeError(
                    f"{output} does not reproduce the layout of output {index} "
                    "of the compiled call"
                )
            spread = (e2.double() - e.double()).abs().nan_to_num().max().item()
            torch.testing.assert_close(a, e, atol=4 * spread, rtol=1e-5, equal_nan=True)


def module_text(
    repro_id: str, shape: str, configs_note: str, code: str, source_hash: str
) -> str:
    return (
        HEADER.format(
            repro_id=repro_id,
            shape=shape,
            configs_note=configs_note,
            source_hash=source_hash,
        )
        + code.rstrip("\n")
        + "\n"
        + FOOTER
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("repro_id")
    parser.add_argument(
        "--shape",
        default=None,
        help="shape hash (default: the repro's selection.json point, else its first)",
    )
    parser.add_argument(
        "--configs-from",
        type=Path,
        default=None,
        help="a directory of Helion autotune cache entries (*.best_config); "
        "without it, every kernel autotunes",
    )
    parser.add_argument(
        "--require-configs",
        action="store_true",
        help="fail on a kernel --configs-from has no config for, rather than "
        "autotune it",
    )
    parser.add_argument(
        "--configs-note",
        default=None,
        help="where the configs came from, for the file's header (default: "
        "the effort of the autotune that would run)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="default: inductor_pretuned/<repro_id>.py",
    )
    args = parser.parse_args()
    cache = Path(tempfile.mkdtemp(prefix="bb-inductor-pretuned-"))
    # Private caches: an Inductor cache would hand back code generated by
    # another tree, and a Helion cache configs no --configs-from entry chose.
    os.environ["TORCHINDUCTOR_CACHE_DIR"] = str(cache / "inductor")
    os.environ["HELION_CACHE_DIR"] = str(cache / "helion")
    try:
        write(args)
    finally:
        shutil.rmtree(cache, ignore_errors=True)


def write(args: argparse.Namespace) -> None:
    # torch is imported only after main() points the caches at private ones.
    import torch
    from torch._inductor.utils import run_and_get_code

    from helion.autotuner.base_cache import should_skip_cache
    from helion.autotuner.metrics import register_post_autotune_hook
    from helion.autotuner.metrics import remove_post_autotune_hook

    shape = args.shape or common.default_shape(args.repro_id)
    backend = common.inductor_helion_options()["helion.backend"]
    if args.output is None and backend != common.INDUCTOR_PRETUNED_BACKEND:
        raise SystemExit(
            f"inductor_pretuned/ holds {common.INDUCTOR_PRETUNED_BACKEND} code "
            f"(common.INDUCTOR_PRETUNED_BACKEND), and helion.inductor's backend is "
            f"{backend}: run under HELION_BACKEND={common.INDUCTOR_PRETUNED_BACKEND}, "
            "or write elsewhere with --output"
        )
    if args.configs_from is not None and should_skip_cache():
        # A kernel then skips the cache lookup --configs-from answers, and
        # autotunes instead.
        raise SystemExit("--configs-from: HELION_SKIP_CACHE skips its lookups")
    instance = common.load_repro_module(args.repro_id).Repro()
    compiled = common.compile_inductor(
        args.repro_id, shape, instance, impl="inductor_helion"
    )
    entries = config_entries(args.configs_from)
    matched: list[str] = []
    searched: list[object] = []
    register_post_autotune_hook(searched.append)
    try:
        with (
            common.env_override(HELION_FORCE_AUTOTUNE="0"),
            configs_from(entries, required=args.require_configs, matched=matched),
            torch.no_grad(),
        ):
            torch.manual_seed(0)
            expected, codes = run_and_get_code(
                compiled, *common.make_inputs(args.repro_id, shape, seed=0)
            )
            # Again, to tell the outputs a call does not reproduce itself
            # (atomic accumulation, sum_sum_sum_d2c97d17f3dc's scatter-add).
            torch.manual_seed(0)
            again = compiled(*common.make_inputs(args.repro_id, shape, seed=0))
        torch.cuda.synchronize()
    finally:
        remove_post_autotune_hook(searched.append)
    if len(codes) != 1:
        raise RuntimeError(f"expected one output module, got {len(codes)}")
    code, kernels = pin(codes[0])
    # A kernel that neither matched an entry nor searched ran a config no
    # search chose: HELION_AUTOTUNE_EFFORT=none takes the default one.
    unsearched = kernels - len(set(matched)) - len(searched)
    if args.require_configs and len(set(matched)) != kernels:
        raise LookupError(
            f"{len(set(matched))} of {kernels} kernels took a config from "
            "--configs-from (--require-configs)"
        )
    if unsearched > 0:
        raise RuntimeError(
            f"{unsearched} of {kernels} kernels neither matched a --configs-from "
            "entry nor autotuned (HELION_AUTOTUNE_EFFORT=none?)"
        )
    effort = common.inductor_helion_options()["helion.autotune_effort"]
    # The GPU the configs were picked on, which bench.py records with the
    # note (configs_from): a config is tuned for one.
    device = torch.cuda.get_device_name()
    note = args.configs_note or (
        f"{len(set(matched))} of {kernels} from --configs-from, the others autotuned "
        f"at effort {effort}, on {device}"
        if entries
        else f"autotuned at effort {effort} on {device}"
    )
    output = args.output or common.inductor_pretuned_path(args.repro_id)
    output.parent.mkdir(parents=True, exist_ok=True)
    # Written beside the file and checked before it replaces it: a module that
    # fails the check leaves the file as it was.
    written = output.with_name(f".{output.name}.{os.getpid()}.py")
    written.write_text(
        module_text(args.repro_id, shape, note, code, common.inductor_source_hash())
    )
    try:
        module = common.load_inductor_pretuned(args.repro_id, shape, path=written)
        with torch.no_grad():
            torch.manual_seed(0)
            actual = module.forward(common.make_inputs(args.repro_id, shape, seed=0))
        torch.cuda.synchronize()
        check_reproduced(output, expected, again, actual)
        os.replace(written, output)
    finally:
        written.unlink(missing_ok=True)
    print(
        f"{output}: {kernels} Helion kernels pinned "
        f"({len(set(matched))} from --configs-from)"
    )


if __name__ == "__main__":
    main()
