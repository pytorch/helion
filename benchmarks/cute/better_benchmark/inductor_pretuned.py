"""Write helion.inductor's output code for a better-benchmark repro, each Helion
kernel pinned to a tuned config, as ``inductor_pretuned/<repro_id>.py``, the
code ``bench.py --impls inductor_helion_pretuned`` times.

Compiles the repro at one shape point with helion.inductor's backend
(``common.inductor_helion_options()``) in private Inductor and Helion caches
and calls it twice, the second time to tell the outputs a call does not
reproduce itself. Each Helion kernel takes its config from
``--configs-from``, a directory of Helion autotune cache entries
(``*.best_config``: the ``HELION_CACHE_DIR`` of an earlier run that autotuned
these kernels, such as the ``cache_*/helion`` directories of bench runs of
``--impls inductor_helion``), matched on what decides a config: the hash of
the kernel's generated source, its input specialization, the GPU and the
backend's extra cache key. The entry's ``config_spec_hash``, which also covers
the compiler's seed configs, may differ: a kernel whose code and inputs did
not change keeps its config across a change of seeds. A kernel that no entry
matches autotunes, at HELION_AUTOTUNE_EFFORT (full when unset), unless
``--require-configs``. The output module is then written with each kernel's
decorator pinned to the config the kernel ran with
(``BoundKernel.format_kernel_decorator``) and checked: called on the same
inputs from the same random state, it must return the compiled call's outputs
bit for bit in the same layout (same code, same configs: identical()), -0.0
and NaN payloads included, except for an output
that the compiled call does not reproduce itself (atomic accumulation), which
must be within four times the call's own difference plus 1e-5 relative. The
module records helion.inductor's source hash (SOURCE_HASH), and loading it
from another helion.inductor warns. The files in inductor_pretuned/ are
CuTe's (common.INDUCTOR_PRETUNED_BACKEND): write them under HELION_BACKEND=cute.

Example::

    HELION_BACKEND=cute python benchmarks/cute/better_benchmark/inductor_pretuned.py \\
        var_mean_004f9a9ea198 --configs-from /tmp/run/cache_var_mean_004f9a9ea198/helion
"""

